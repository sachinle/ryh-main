    <script>
        document.addEventListener('DOMContentLoaded', function () {
            var counters = document.querySelectorAll('.counter');
            var speed = 200; // Adjust the speed of counting

            // Function to check if an element is in the viewport
            function isInViewport(element) {
                var rect = element.getBoundingClientRect();
                return (
                    rect.top >= 0 &&
                    rect.left >= 0 &&
                    rect.bottom <= (window.innerHeight || document.documentElement.clientHeight) &&
                    rect.right <= (window.innerWidth || document.documentElement.clientWidth)
                );
            }

            function updateCount(counter, target, speed) {
                var count = 0;
                var increment = target / speed;

                function incrementCount() {
                    count += increment;
                    if (count < target) {
                        counter.innerText = (target % 1 === 0) ? Math.ceil(count) : count.toFixed(1);
                        setTimeout(incrementCount, 1);
                    } else {
                        counter.innerText = target;
                    }
                }

                incrementCount();
            }

            counters.forEach(counter => {
                // Check if the counter element is initially in the viewport
                if (isInViewport(counter)) {
                    var target = parseFloat(counter.innerText);
                    updateCount(counter, target, speed);
                }
            });

            // Add scroll event listener to check if elements become visible while scrolling
            window.addEventListener('scroll', function () {
                counters.forEach(counter => {
                    if (!counter.dataset.visible && isInViewport(counter)) {
                        counter.dataset.visible = true;

                        var target = parseFloat(counter.innerText);
                        updateCount(counter, target, speed);
                    }
                });
            });
        });
    </script>
